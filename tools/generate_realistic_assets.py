#!/usr/bin/env python3
"""
Open City C++ v1.3.0 — Procedural 3D CAD Spline, Landmark Geometry & Shader LUT Generator
=========================================================================================
Generates `src/render/GeneratedRealisticAssets.hpp` containing:
  1. 16-tap rotated Poisson disk filter kernel for soft PCF shadows.
  2. True hyperbolic cosine catenary cable curve coordinates for the Golden Bay Suspension Bridge.
  3. 12-gondola Sunset Beach Ferris Wheel spoke & cabin ring geometry tables.
"""

from __future__ import annotations
import math
import pathlib


def generate_poisson_16() -> list[tuple[float, float]]:
    # Golden-angle spiral distribution on unit disc for low-discrepancy 16-tap soft shadows
    pts: list[tuple[float, float]] = []
    golden_angle = math.pi * (3.0 - math.sqrt(5.0))
    for i in range(16):
        r = math.sqrt((i + 0.5) / 16.0)
        theta = i * golden_angle
        pts.append((r * math.cos(theta), r * math.sin(theta)))
    return pts


def generate_suspension_catenary(segments: int = 24) -> list[tuple[float, float]]:
    # True hyperbolic cosine catenary curve y(u) = a * (cosh(u / a) - 1) normalized to [0, 1]
    a = 1.15
    denom = math.cosh(1.0 / a) - 1.0
    pts: list[tuple[float, float]] = []
    for i in range(segments + 1):
        u = -1.0 + 2.0 * (i / float(segments))  # [-1, +1] along span
        sag = (math.cosh(u / a) - 1.0) / denom  # 0 at center, 1 at tower tops
        pts.append((u, sag))
    return pts


def generate_ferris_wheel_spokes(count: int = 12) -> list[tuple[float, float]]:
    pts: list[tuple[float, float]] = []
    for i in range(count):
        ang = (2.0 * math.pi * i) / float(count)
        pts.append((math.cos(ang), math.sin(ang)))
    return pts


def build_header() -> str:
    poisson = generate_poisson_16()
    catenary = generate_suspension_catenary(24)
    ferris = generate_ferris_wheel_spokes(12)

    lines: list[str] = [
        "// AUTO-GENERATED BY tools/generate_realistic_assets.py (Python 3 CAD & Shader Bakery)",
        "// Do not edit manually; re-run `python3 tools/generate_realistic_assets.py` to regenerate.",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "namespace oc::generated {",
        "",
        "struct Vec2f {",
        "    float x;",
        "    float y;",
        "};",
        "",
        "// 16-tap Golden-Angle Poisson Disk kernel for soft shadow filtering",
        "inline constexpr std::array<Vec2f, 16> kPoissonDisk16 = {{",
    ]
    for x, y in poisson:
        lines.append(f"    {{{x:+.6f}f, {y:+.6f}f}},")
    lines.append("}};")
    lines.append("")

    lines.append("// 25-station hyperbolic cosine catenary curve (u in [-1, 1], sag in [0, 1])")
    lines.append("inline constexpr std::array<Vec2f, 25> kSuspensionBridgeCatenary = {{")
    for u, sag in catenary:
        lines.append(f"    {{{u:+.6f}f, {sag:+.6f}f}},")
    lines.append("}};")
    lines.append("")

    lines.append("// 12-spoke Sunset Beach Ferris Wheel unit circle LUT")
    lines.append("inline constexpr std::array<Vec2f, 12> kFerrisWheelRing12 = {{")
    for c, s in ferris:
        lines.append(f"    {{{c:+.6f}f, {s:+.6f}f}},")
    lines.append("}};")
    lines.append("")

    lines.extend([
        "} // namespace oc::generated",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    repo_root = pathlib.Path(__file__).resolve().parent.parent
    target = repo_root / "src" / "render" / "GeneratedRealisticAssets.hpp"
    target.parent.mkdir(parents=True, exist_ok=True)
    content = build_header()
    target.write_text(content, encoding="utf-8")
    print(f"[generate_realistic_assets.py] Generated {target} ({len(content)} bytes)")


if __name__ == "__main__":
    main()

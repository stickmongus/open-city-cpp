#!/usr/bin/env python3
"""Compile all Vulkan GLSL 450 shaders to validated SPIR-V 1.0 and generate src/render/VulkanShadersSpv.hpp."""

import os
import shutil
import subprocess
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIR = os.path.join(ROOT, "src", "render", "shaders")
OUT_HPP = os.path.join(ROOT, "src", "render", "VulkanShadersSpv.hpp")

SHADERS = [
    ("kDepthVertSpv", "depth.vert"),
    ("kDepthFragSpv", "depth.frag"),
    ("kSkyVertSpv",   "sky.vert"),
    ("kSkyFragSpv",   "sky.frag"),
    ("kWorldVertSpv", "world.vert"),
    ("kWorldFragSpv", "world.frag"),
    ("kPostVertSpv",  "post.vert"),
    ("kPostFragSpv",  "post.frag"),
    ("kUi2dVertSpv",  "ui2d.vert"),
    ("kUi2dFragSpv",  "ui2d.frag"),
]

def find_compiler():
    for candidate in ["/tmp/vktools/bin/glslangValidator", shutil.which("glslangValidator"), shutil.which("glslc")]:
        if candidate and os.path.exists(candidate):
            return candidate
    raise RuntimeError("No glslangValidator or glslc found!")

def compile_spv(compiler, src_path, tmp_spv):
    if os.path.basename(compiler) == "glslc":
        cmd = [compiler, "--target-env=vulkan1.0", "-O", src_path, "-o", tmp_spv]
    else:
        cmd = [compiler, "-V", "--target-env", "vulkan1.0", src_path, "-o", tmp_spv]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"FAILED compiling {src_path}:\n{res.stdout}\n{res.stderr}", file=sys.stderr)
        sys.exit(1)
    with open(tmp_spv, "rb") as f:
        data = f.read()
    assert len(data) % 4 == 0 and len(data) >= 20
    words = struct.unpack(f"<{len(data)//4}I", data)
    assert words[0] == 0x07230203, "Invalid SPIR-V magic!"
    return words

def main():
    compiler = find_compiler()
    print(f"Using Vulkan SPIR-V compiler: {compiler}")
    lines = [
        "#pragma once",
        "// Auto-generated by tools/compile_vulkan_shaders.py from src/render/shaders/*.{vert,frag}",
        "// Pre-compiled Khronos SPIR-V 1.0 bytecode for zero-stutter Vulkan 1.0+ execution on Android/Windows/Linux.",
        "#include <cstdint>",
        "#include <cstddef>",
        "",
        "namespace oc::spv {",
        ""
    ]
    os.makedirs("/tmp/spv_out", exist_ok=True)
    for var_name, filename in SHADERS:
        src = os.path.join(SHADER_DIR, filename)
        tmp = os.path.join("/tmp/spv_out", filename + ".spv")
        words = compile_spv(compiler, src, tmp)
        print(f"  Compiled {filename:12s} -> {len(words)*4:6d} bytes ({len(words)} words) OK")
        lines.append(f"inline constexpr std::uint32_t {var_name}[{len(words)}] = {{")
        for i in range(0, len(words), 8):
            chunk = ", ".join(f"0x{w:08x}u" for w in words[i:i+8])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append(f"inline constexpr std::size_t {var_name}Size = sizeof({var_name});")
        lines.append("")
    lines.append("} // namespace oc::spv")
    lines.append("")
    with open(OUT_HPP, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated {OUT_HPP} successfully!")

if __name__ == "__main__":
    main()

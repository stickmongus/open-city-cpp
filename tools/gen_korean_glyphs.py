#!/usr/bin/env python3
"""Scan src/ for all non-ASCII Unicode characters and emit src/ui/AndroidKoreanGlyphs.hpp.

Packing only the exact Unicode codepoints referenced by the game (plus verification
glyphs) keeps the Android OpenGL ES 3.0 font atlas compact (1024px wide, <80ms startup)
while guaranteeing zero missing Korean characters on mobile.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "src"
OUT_FILE = SRC_DIR / "ui" / "AndroidKoreanGlyphs.hpp"

# Required Hangul verification glyphs referenced by HudRenderer.cpp on Android
REQUIRED_CODEPOINTS = {
    0xAC00,  # '가'
    0xB8CC,  # '료'
    0xC2DC,  # '시'
    0xCC28,  # '차'
}


def collect_codepoints() -> list[int]:
    cps: set[int] = set(REQUIRED_CODEPOINTS)
    for ext in ("*.hpp", "*.cpp"):
        for path in sorted(SRC_DIR.rglob(ext)):
            if path.resolve() == OUT_FILE.resolve():
                continue
            text = path.read_text(encoding="utf-8")
            for ch in text:
                cp = ord(ch)
                if cp > 0x7E:
                    cps.add(cp)
    return sorted(cps)


def main() -> None:
    cps = collect_codepoints()
    lines = [
        "#pragma once",
        "",
        "// Auto-generated by tools/gen_korean_glyphs.py — DO NOT EDIT MANUALLY.",
        f"// Exact non-ASCII codepoint table ({len(cps)} unique glyphs) for fast Android OpenGL ES 3.0 atlas packing.",
        "",
        "namespace oc {",
        "",
        "inline constexpr int kAndroidKoreanCodepoints[] = {",
    ]
    row: list[str] = []
    for cp in cps:
        row.append(f"0x{cp:04X}")
        if len(row) == 12:
            lines.append("    " + ", ".join(row) + ",")
            row.clear()
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.extend([
        "};",
        "",
        "} // namespace oc",
        "",
    ])
    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUT_FILE.relative_to(ROOT)} with {len(cps)} unique non-ASCII codepoints.")


if __name__ == "__main__":
    main()
